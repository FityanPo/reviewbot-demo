package demo;

/** Petite calculatrice servant de projet de démonstration pour ReviewBot. */
public class Calc {

    /** Additionne deux entiers. */
    public int add(int a, int b) {
        return a + b;
    }

    /** Soustrait b de a. */
    public int subtract(int a, int b) {
        return a - b;
    }
}
